"""Claude host check. Standard library only (Python 3.8+); no Anthropic account, no sign-in, no model calls.

1. Static checks from the Claude plugin docs and the directory's pre-submission checklist: .claude-plugin/plugin.json
   (name rules incl. reserved names, version, description, author, license, homepage URL), .claude-plugin/marketplace.json
   (name, owner, plugin source "./"), .mcp.json (stdio, file under ${CLAUDE_PLUGIN_ROOT}, workspace under
   ${CLAUDE_PLUGIN_DATA}), skill/command/agent front matter (description is one text value), no top-level bin/, no hooks,
   README of 40+ words outside code blocks, LICENSE present, no binary files (sample PDFs generated by
   make_sample_pdfs.py are git-ignored and not packed).
2. Builds dist/spindoctor-qwerty.plugin (tools/build_plugin.py) and checks it the way the claude.ai upload does:
   plugin.json at .claude-plugin/plugin.json of the zip root, no bin/, <= 5000 files, <= 200 MB, text files only.
3. With the REAL Claude Code CLI (set CLAUDE=/path/to/claude or have `claude` on PATH), in a throw-away HOME:
   `claude plugin validate` (repo + manifest + the unzipped .plugin), `claude plugin marketplace add <repo>`,
   `claude plugin install spindoctor-qwerty@spindoctor-qwerty-claude`, `claude plugin list`, `claude plugin details`
   (5 skills = skill + 4 commands, 1 agent, 1 MCP server), `claude mcp list` (Claude Code starts the plugin's server and
   reports it Connected), and `claude --plugin-dir <unzipped .plugin> mcp list`.
4. End-to-end: tests/e2e_mcp.py through the server declared in .mcp.json, resolved the way Claude Code documents it
   (${CLAUDE_PLUGIN_ROOT}/${CLAUDE_PLUGIN_DATA} in command/args/env, both exported) against the plugin copy Claude Code
   installed (or the repo when Claude Code is absent). Calling tools through Claude Code itself needs a signed-in
   session, so the tool calls are host-simulated.

usage: python3 tests/claude_host_check.py [REPO_DIR]"""
import json, os, re, shutil, subprocess, sys, tempfile, zipfile
from urllib.parse import urlparse

HERE = os.path.dirname(os.path.abspath(__file__))
PLUGIN_ID = "spindoctor-qwerty@spindoctor-qwerty-claude"
TEXT = (".py", ".md", ".json", ".txt", ".csv", ".html", ".q", ".svg", "")


def frontmatter(path):
    m = re.match(r"^---\n(.*?)\n---\n", open(path, encoding="utf-8").read(), re.S)
    return dict(re.findall(r"^([A-Za-z_-]+):\s*(.+)$", m.group(1), re.M)) if m else None


def reserved(name):
    n = re.sub(r"[-_. ]+", "-", name.lower())
    return n.startswith(("claude-", "anthropic-", "anthropics-", "cc-plugin-")) or n in ("claude", "anthropic", "anthropics", "claude-code", "claude-mods") \
        or re.search(r"(official-(claude|anthropic))|((claude|anthropic)-official)", n)


def main():
    repo = os.path.abspath(sys.argv[1]) if len(sys.argv) > 1 else os.path.dirname(HERE)
    ok = True; mode = "host-simulated"

    def T(name, cond, detail=""):
        nonlocal ok
        ok = ok and bool(cond); print(("PASS " if cond else "FAIL ") + name + ("" if cond else "  -- " + str(detail)[:600])); sys.stdout.flush()

    load = lambda *p: json.load(open(os.path.join(*p), encoding="utf-8"))
    pj = load(repo, ".claude-plugin", "plugin.json"); mk = load(repo, ".claude-plugin", "marketplace.json"); mj = load(repo, ".mcp.json")
    name = pj.get("name", "")
    T("plugin.json: kebab-case name, not a reserved name, displayName, version 1.1.0, description, author, GPL-3.0-or-later, homepage parses as a URL",
      re.match(r"^[a-z0-9]+(-[a-z0-9]+)*$", name) and not reserved(name) and pj.get("displayName") and pj.get("version") == "1.1.0" and pj.get("description")
      and pj.get("author", {}).get("name") == "RUSSELL PHILIP SMITHSON" and pj.get("license") == "GPL-3.0-or-later" and urlparse(pj.get("homepage", "")).scheme == "https", pj)
    e = (mk.get("plugins") or [{}])[0]
    T("marketplace.json: name (not reserved), owner.name, one entry for the plugin at the repo root (source \"./\"), same version",
      mk.get("name") == "spindoctor-qwerty-claude" and not reserved(mk["name"]) and mk.get("owner", {}).get("name") and e.get("name") == name
      and e.get("source") in ("./", ".") and e.get("version") == pj["version"], mk)
    s = mj["mcpServers"]["spindoctor-qwerty"]
    T(".mcp.json: stdio server running a plugin file with plain arguments; workspace under ${CLAUDE_PLUGIN_DATA}",
      s.get("type", "stdio") == "stdio" and s["command"] == "python3" and len(s["args"]) == 1 and s["args"][0].startswith("${CLAUDE_PLUGIN_ROOT}/")
      and os.path.isfile(s["args"][0].replace("${CLAUDE_PLUGIN_ROOT}", repo)) and s["env"]["SPINDOCTOR_WORKSPACE"].startswith("${CLAUDE_PLUGIN_DATA}/"), s)
    md = [os.path.join(repo, "skills", "spindoctor-qwerty", "SKILL.md")] + [os.path.join(repo, d, f) for d in ("commands", "agents") for f in sorted(os.listdir(os.path.join(repo, d)))]
    fms = {os.path.relpath(p, repo): frontmatter(p) for p in md}
    T("skill, 4 commands and 1 agent: front matter parses, description is one text value", len(md) == 6 and all(f and f.get("description") and not f["description"].startswith(("[", "-")) for f in fms.values()), fms)
    T("no top-level bin/ (claude.ai and Cowork refuse it), no hooks", not os.path.exists(os.path.join(repo, "bin")) and not os.path.exists(os.path.join(repo, "hooks")) and "hooks" not in pj)
    readme = re.sub(r"```.*?```", "", open(os.path.join(repo, "README.md"), encoding="utf-8").read(), flags=re.S)
    T("README.md has 40+ words outside code blocks; LICENSE present", len(readme.split()) >= 40 and os.path.isfile(os.path.join(repo, "LICENSE")), len(readme.split()))
    bad = [os.path.relpath(os.path.join(r, f), repo) for r, ds, fs in os.walk(repo) if ".git" not in r.split(os.sep) and "dist" not in r.split(os.sep) and "__pycache__" not in r
           for f in fs if os.path.splitext(f)[1].lower() not in TEXT and not (f.endswith(".pdf") and r.endswith(os.path.join("examples", "theory")))]
    T("only text files in the plugin (no .pdf/.zip/executables, which the directory holds for review)", not bad, bad)

    sys.dont_write_bytecode = True; sys.path.insert(0, os.path.join(repo, "tools")); import build_plugin
    out, h, n = build_plugin.build(tempfile.mkdtemp(prefix="sdq_plugin_"))
    with zipfile.ZipFile(out) as z: names = z.namelist(); size = sum(i.file_size for i in z.infolist())
    T(".plugin zip: .claude-plugin/plugin.json at the root, no bin/, %d files, %.1f KB, text only" % (n, size / 1024.0),
      ".claude-plugin/plugin.json" in names and not any(x.startswith("bin/") for x in names) and n <= 5000 and size <= 200 * 2 ** 20
      and all(os.path.splitext(x)[1].lower() in TEXT for x in names), names[:5])
    unz = tempfile.mkdtemp(prefix="sdq_unzipped_"); zipfile.ZipFile(out).extractall(unz)
    root = repo
    claude = os.environ.get("CLAUDE") or shutil.which("claude")
    if claude:
        mode = "real Claude Code (tool calls host-simulated)"
        home = tempfile.mkdtemp(prefix="sdq_claude_home_"); env = dict(os.environ, HOME=home)
        run = lambda *a: subprocess.run([claude] + list(a), env=env, cwd=home, stdin=subprocess.DEVNULL, stdout=subprocess.PIPE, stderr=subprocess.STDOUT, text=True, timeout=180)
        v = run("--version").stdout.strip().splitlines()[-1]
        rs = [run("plugin", "validate", p) for p in (repo, os.path.join(repo, ".claude-plugin", "plugin.json"), unz)]
        T("%s: claude plugin validate passes for the marketplace, the plugin manifest and the unzipped .plugin" % v,
          all(r.returncode == 0 and "Validation passed" in r.stdout for r in rs), [r.stdout[-300:] for r in rs])
        r = run("plugin", "marketplace", "add", repo)
        T("claude plugin marketplace add <repo>", r.returncode == 0 and "spindoctor-qwerty-claude" in r.stdout, r.stdout)
        r = run("plugin", "install", PLUGIN_ID)
        T("claude plugin install %s" % PLUGIN_ID, r.returncode == 0 and "Successfully installed" in r.stdout, r.stdout)
        r = run("plugin", "list")
        T("claude plugin list: 1.1.0, enabled", PLUGIN_ID in r.stdout and "Version: 1.1.0" in r.stdout and "enabled" in r.stdout, r.stdout)
        r = run("plugin", "details", PLUGIN_ID)
        T("claude plugin details: 5 skills (skill + 4 commands), 1 agent, 1 MCP server, 0 hooks",
          re.search(r"Skills \(5\)", r.stdout) and re.search(r"Agents \(1\)\s+qwerty-helper", r.stdout) and re.search(r"MCP servers \(1\)\s+spindoctor-qwerty", r.stdout) and "Hooks (0)" in r.stdout, r.stdout)
        r = run("mcp", "list")
        T("claude mcp list: Claude Code starts the plugin's server -> Connected", re.search(r"plugin:spindoctor-qwerty:spindoctor-qwerty: python3 \S+/skills/spindoctor-qwerty/scripts/spindoctor_mcp\.py - \S* ?Connected", r.stdout), r.stdout)
        r = run("--plugin-dir", unz, "mcp", "list")
        T("claude --plugin-dir <unzipped .plugin> mcp list -> Connected", "Connected" in r.stdout and unz in r.stdout, r.stdout)
        inst = load(home, ".claude", "plugins", "installed_plugins.json")
        paths = [x.get("installPath") for v_ in inst.get("plugins", {}).values() for x in (v_ if isinstance(v_, list) else [v_]) if isinstance(x, dict)]
        root = next((p for p in paths if p and os.path.isdir(p)), repo)
    else:
        print("SKIP real Claude Code CLI not found (set CLAUDE=/path/to/claude)")
    data = tempfile.mkdtemp(prefix="sdq_plugin_data_")
    sub = lambda x: x.replace("${CLAUDE_PLUGIN_ROOT}", root).replace("${CLAUDE_PLUGIN_DATA}", data)
    cmd = [os.environ.get("SPINDOCTOR_PYTHON") or sub(s["command"])] + [sub(a) for a in s["args"]]
    env2 = dict(os.environ, **{k: sub(v) for k, v in s.get("env", {}).items()}); env2.update(CLAUDE_PLUGIN_ROOT=root, CLAUDE_PLUGIN_DATA=data)
    ex = os.path.join(root, "skills", "spindoctor-qwerty", "examples", "theory")
    r = subprocess.run([sys.executable, os.path.join(HERE, "e2e_mcp.py"), "--server"] + cmd + ["--examples", ex, "--out", os.path.join(data, "e2e_results.json")], env=env2)
    T("end-to-end through the server declared in .mcp.json (plugin root: %s)" % ("Claude Code's installed copy" if root != repo else "repo"), r.returncode == 0)
    print("HOST-CHECK (%s)" % mode, "PASS" if ok else "FAIL")
    return 0 if ok else 1


if __name__ == "__main__":
    sys.exit(main())
